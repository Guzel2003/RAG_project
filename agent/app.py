# agent/app.py
import gradio as gr
from agent.brain import get_agent_response
from agent.memory import memory

# Для веб-интерфейса используем фиксированный ID пользователя
DEMO_USER_ID = 999


def chat_with_agent(message, history):
    """
    Эта функция связывает интерфейс Gradio с нашим агентом.
    message: то, что написал пользователь
    history: история переписки (Gradio передает её для отображения)
    """
    # Вызываем нашего агента, который уже умеет работать с LLM и памятью
    response = get_agent_response(DEMO_USER_ID, message)

    # Возвращаем ответ. Gradio сам красиво оформит его в чате.
    return response


# Создаем интерфейс чата (убрали theme, чтобы избежать ошибок версий)
demo = gr.ChatInterface(
    fn=chat_with_agent,
    title="🏗️ Агент-инженер для расчета конструкций",
    description=(
        "Я помогаю рассчитывать элементы строительных конструкций. "
        "Напишите, что нужно рассчитать (например: 'деревянная балка длиной 4м, нагрузка 200 кг/м'), "
        "и я уточню детали или проведу расчет."
    ),
    examples=[
        "Какие документы прилагаются к заявлению о выдаче разрешения на ввод объекта в эксплуатацию?",
        "Что должно быть указано на информационном щите при въезде на строительную площадку?",
        "В какие сроки нужно оградить строительную площадку?",
        "Какие графические параметры должны содержать исполнительные геодезические схемы?",
        "Как оформить кредит на строительство частного дома?"
    ]
)

if __name__ == "__main__":
    # Очищаем память при каждом новом запуске сервера
    memory.clear_history(DEMO_USER_ID)
    print("🚀 Запуск веб-интерфейса агента...")

    # share=True создаст публичную ссылку, которую можно скинуть преподавателю!
    demo.launch(share=True, inbrowser=True)